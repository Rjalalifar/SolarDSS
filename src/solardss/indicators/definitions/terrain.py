"""Terrain vocabulary. Slope/aspect may be derived by Horn when a DEM is supplied."""

from __future__ import annotations

from solardss.indicators.contracts import (
    Controllability,
    IndicatorCategory,
    IndicatorRole,
    OptimizationDirection,
    RequirementLevel,
    SourceType,
)
from solardss.indicators.defaults import (
    ALL_MODES,
    ALL_PROJECTS,
    DEM_ELEVATION_ZONAL,
    GROUND_PROJECTS,
    HORN_SLOPE_ASPECT,
    RILEY_TRI,
    TERRAIN_FROM_DEM,
)
from solardss.indicators.factory import define
from solardss.indicators.ids import IndicatorId

TERRAIN_INDICATORS = (
    define(
        IndicatorId.TERRAIN_ELEVATION,
        name="Elevation",
        description="Surface elevation from a DEM. SolarDSS does not invent a DEM.",
        category=IndicatorCategory.TERRAIN,
        role=IndicatorRole.TERRAIN_INDICATOR,
        controllability=Controllability.UNCONTROLLABLE,
        unit="m",
        optimization_direction=OptimizationDirection.NONE,
        applicable_decision_modes=ALL_MODES,
        applicable_project_types=ALL_PROJECTS,
        preferred_source_types=(SourceType.DEM,),
        required_or_optional=RequirementLevel.OPTIONAL,
        derivation_method=DEM_ELEVATION_ZONAL,
    ),
    define(
        IndicatorId.TERRAIN_SLOPE_MEAN,
        name="Mean terrain slope",
        description="Mean slope in degrees. Computable from a regular DEM via Horn (1981).",
        category=IndicatorCategory.TERRAIN,
        role=IndicatorRole.TERRAIN_INDICATOR,
        controllability=Controllability.DERIVED,
        unit="deg",
        optimization_direction=OptimizationDirection.MINIMIZE,
        applicable_decision_modes=ALL_MODES,
        applicable_project_types=GROUND_PROJECTS,
        preferred_source_types=(SourceType.DEM, SourceType.DERIVED_FROM_REGISTERED_INDICATORS),
        required_or_optional=RequirementLevel.REQUIRED,
        derivation_method=HORN_SLOPE_ASPECT,
        aliases=("slope_deg",),
        notes="Rooftop slope is ROOF_SLOPE, not this indicator.",
    ),
    define(
        IndicatorId.TERRAIN_SLOPE_MAX,
        name="Maximum terrain slope",
        description="Maximum slope in the site or cell. Same Horn derivation as mean slope.",
        category=IndicatorCategory.TERRAIN,
        role=IndicatorRole.TERRAIN_INDICATOR,
        controllability=Controllability.DERIVED,
        unit="deg",
        optimization_direction=OptimizationDirection.MINIMIZE,
        applicable_decision_modes=ALL_MODES,
        applicable_project_types=GROUND_PROJECTS,
        preferred_source_types=(SourceType.DEM, SourceType.DERIVED_FROM_REGISTERED_INDICATORS),
        required_or_optional=RequirementLevel.OPTIONAL,
        derivation_method=HORN_SLOPE_ASPECT,
    ),
    define(
        IndicatorId.TERRAIN_ASPECT,
        name="Terrain aspect",
        description=(
            "Direction of steepest descent, degrees clockwise from north, via Horn (1981). "
            "Equator-facing preference is a policy target, not implied here."
        ),
        category=IndicatorCategory.TERRAIN,
        role=IndicatorRole.TERRAIN_INDICATOR,
        controllability=Controllability.DERIVED,
        unit="deg",
        optimization_direction=OptimizationDirection.TARGET,
        applicable_decision_modes=ALL_MODES,
        applicable_project_types=GROUND_PROJECTS,
        preferred_source_types=(SourceType.DEM, SourceType.DERIVED_FROM_REGISTERED_INDICATORS),
        required_or_optional=RequirementLevel.OPTIONAL,
        derivation_method=HORN_SLOPE_ASPECT,
        aliases=("aspect_deg",),
    ),
    define(
        IndicatorId.TERRAIN_RUGGEDNESS,
        name="Terrain ruggedness",
        description="Terrain ruggedness index (Riley et al. 1999 TRI) from a DEM.",
        category=IndicatorCategory.TERRAIN,
        role=IndicatorRole.TERRAIN_INDICATOR,
        controllability=Controllability.DERIVED,
        unit="m",
        optimization_direction=OptimizationDirection.MINIMIZE,
        applicable_decision_modes=ALL_MODES,
        applicable_project_types=GROUND_PROJECTS,
        preferred_source_types=(SourceType.DEM, SourceType.CALLER_PROVIDED),
        required_or_optional=RequirementLevel.OPTIONAL,
        derivation_method=RILEY_TRI,
        notes="TRI is metres of neighborhood elevation difference, not a slope angle.",
    ),
    define(
        IndicatorId.TERRAIN_HORIZON_OBSTRUCTION,
        name="Horizon obstruction",
        description="Horizon/far-field obstruction angle. Not computed by SolarDSS yet.",
        category=IndicatorCategory.TERRAIN,
        role=IndicatorRole.TERRAIN_INDICATOR,
        controllability=Controllability.DERIVED,
        unit="deg",
        optimization_direction=OptimizationDirection.MINIMIZE,
        applicable_decision_modes=ALL_MODES,
        applicable_project_types=ALL_PROJECTS,
        preferred_source_types=(SourceType.DEM, SourceType.CALLER_PROVIDED),
        required_or_optional=RequirementLevel.OPTIONAL,
        derivation_method=TERRAIN_FROM_DEM,
    ),
    define(
        IndicatorId.TERRAIN_SHADING_POTENTIAL,
        name="Terrain shading potential",
        description="Potential terrain shading of the array. Not computed by SolarDSS yet.",
        category=IndicatorCategory.TERRAIN,
        role=IndicatorRole.TERRAIN_INDICATOR,
        controllability=Controllability.DERIVED,
        unit="1",
        optimization_direction=OptimizationDirection.MINIMIZE,
        applicable_decision_modes=ALL_MODES,
        applicable_project_types=ALL_PROJECTS,
        preferred_source_types=(SourceType.DEM, SourceType.CALLER_PROVIDED),
        required_or_optional=RequirementLevel.OPTIONAL,
        derivation_method=TERRAIN_FROM_DEM,
        notes="Do not equate slope with shading.",
    ),
)
