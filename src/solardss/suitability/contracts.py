"""Explicit MCDA configuration. Weights are never inferred and never LLM-authored."""

from __future__ import annotations

from enum import Enum

from pydantic import BaseModel, ConfigDict, Field, model_validator

from solardss.core.status import EvaluationStatus, FeasibilityStatus
from solardss.indicators.catalog import registry as default_registry
from solardss.indicators.contracts import IndicatorSpec, OptimizationDirection
from solardss.indicators.registry import IndicatorRegistry
from solardss.provenance.record import ProvenanceRecord
from solardss.suitability.errors import DecisionProfileError, RankingConfigError

_WEIGHT_ATOL = 1e-12


class NormalizationKind(str, Enum):
    """How a criterion is scaled onto ``[0, 1]``. Kind does not imply a weight."""

    BENEFIT = "benefit"
    COST = "cost"
    TARGET = "target"


class OmissionReason(str, Enum):
    """Why a candidate is absent from the ranked or Pareto set."""

    EXCLUDED = "excluded"
    UNKNOWN_FEASIBILITY = "unknown_feasibility"
    INCOMPLETE_INDICATORS = "incomplete_indicators"


class CriterionWeight(BaseModel):
    """One WSM weight. Source, profile, and rationale are required provenance."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    indicator_id: str = Field(min_length=1)
    weight: float
    unit: str = Field(min_length=1)
    source: str = Field(min_length=1)
    profile: str = Field(min_length=1)
    rationale: str = Field(min_length=1)
    normalization: NormalizationKind
    target_value: float | None = None
    range_min: float | None = None
    range_max: float | None = None

    @model_validator(mode="after")
    def _consistent(self) -> CriterionWeight:
        if self.weight != self.weight or self.weight in (float("inf"), float("-inf")):
            raise DecisionProfileError("criterion weight must be finite")
        if self.weight < 0.0:
            raise DecisionProfileError(f"weight for {self.indicator_id!r} is negative")
        if self.normalization is NormalizationKind.TARGET:
            if self.target_value is None:
                raise DecisionProfileError(
                    f"{self.indicator_id}: target normalization requires target_value"
                )
            if self.target_value != self.target_value or self.target_value in (
                float("inf"),
                float("-inf"),
            ):
                raise DecisionProfileError("target_value must be finite")
        elif self.target_value is not None:
            raise DecisionProfileError("target_value is only valid for target normalization")
        if (self.range_min is None) ^ (self.range_max is None):
            raise DecisionProfileError(
                f"{self.indicator_id}: range_min and range_max must be supplied together"
            )
        if (
            self.range_min is not None
            and self.range_max is not None
            and self.range_max < self.range_min
        ):
            raise DecisionProfileError("range_max must be >= range_min")
        return self


class DecisionProfile(BaseModel):
    """Named bundle of criterion weights.

    Example profiles shipped with SolarDSS are labelled ``example=True``. They
    are configuration, not universal truth, and are never applied unless the
    caller passes them in. Weights are never generated by an LLM.
    """

    model_config = ConfigDict(frozen=True, extra="forbid")

    profile_id: str = Field(min_length=1)
    label: str = Field(min_length=1)
    criteria: tuple[CriterionWeight, ...] = Field(min_length=1)
    example: bool = False
    notes: tuple[str, ...] = ()
    normalize_weights: bool = False

    @model_validator(mode="after")
    def _consistent(self) -> DecisionProfile:
        seen: set[str] = set()
        for item in self.criteria:
            if item.indicator_id in seen:
                raise DecisionProfileError(f"duplicate criterion {item.indicator_id!r}")
            seen.add(item.indicator_id)
            if item.profile != self.profile_id:
                raise DecisionProfileError(
                    f"criterion {item.indicator_id!r} profile {item.profile!r} "
                    f"does not match profile_id {self.profile_id!r}"
                )
        total = float(sum(item.weight for item in self.criteria))
        if total <= 0.0:
            raise DecisionProfileError("weights must sum to a positive value")
        if not self.normalize_weights and abs(total - 1.0) > _WEIGHT_ATOL:
            raise DecisionProfileError("weights must sum to 1, or pass normalize_weights=True")
        validate_decision_profile(self)
        if self.example and not any("example" in note.casefold() for note in self.notes):
            raise DecisionProfileError(
                "example profiles must state in notes that they are examples, not universal truth"
            )
        return self

    def resolved_weights(self) -> dict[str, float]:
        """Return non-negative weights that sum to 1."""

        total = float(sum(item.weight for item in self.criteria))
        if self.normalize_weights:
            return {item.indicator_id: item.weight / total for item in self.criteria}
        return {item.indicator_id: item.weight for item in self.criteria}


class ObjectiveSpec(BaseModel):
    """One raw objective for Pareto analysis. Not a WSM weight."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    indicator_id: str = Field(min_length=1)
    direction: OptimizationDirection
    unit: str = Field(min_length=1)
    source: str = Field(min_length=1)
    rationale: str = Field(min_length=1)

    @model_validator(mode="after")
    def _scored_direction(self) -> ObjectiveSpec:
        if self.direction not in {
            OptimizationDirection.MAXIMIZE,
            OptimizationDirection.MINIMIZE,
        }:
            raise RankingConfigError(
                "Pareto objectives require maximize or minimize; target/none are not ranked"
            )
        return self


class NormalizationStats(BaseModel):
    """Range actually used to scale one criterion."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    indicator_id: str = Field(min_length=1)
    kind: NormalizationKind
    range_min: float
    range_max: float
    range_source: str = Field(min_length=1)
    equal_values: bool
    target_value: float | None = None
    unit: str = Field(min_length=1)


class CriterionContribution(BaseModel):
    """Trace of one criterion for one candidate."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    indicator_id: str = Field(min_length=1)
    raw_value: float
    unit: str = Field(min_length=1)
    normalized_value: float
    weight: float
    weighted_contribution: float
    normalization: NormalizationKind
    range_min: float
    range_max: float
    range_source: str = Field(min_length=1)
    target_value: float | None = None
    source: str = Field(min_length=1)
    profile: str = Field(min_length=1)
    rationale: str = Field(min_length=1)


class RankedCandidate(BaseModel):
    """One WSM row. Rank 1 is best. Ties break on ``candidate_id``."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    candidate_id: str = Field(min_length=1)
    score: float
    rank: int = Field(ge=1)
    constraint_status: FeasibilityStatus
    contributions: tuple[CriterionContribution, ...]
    warnings: tuple[str, ...] = ()


class OmittedCandidate(BaseModel):
    """A candidate that was not ranked or placed on the Pareto front."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    candidate_id: str = Field(min_length=1)
    reason: OmissionReason
    constraint_status: FeasibilityStatus
    missing_indicators: tuple[str, ...] = ()


class RankingResult(BaseModel):
    """Deterministic Weighted Sum Model ranking with full per-criterion trace."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    profile_id: str = Field(min_length=1)
    method: str = "weighted_sum_model"
    ranked: tuple[RankedCandidate, ...] = ()
    omitted: tuple[OmittedCandidate, ...] = ()
    criteria: tuple[CriterionWeight, ...]
    used_weights: dict[str, float]
    normalization: tuple[NormalizationStats, ...] = ()
    example_profile: bool = False
    provenance: ProvenanceRecord
    status: EvaluationStatus = EvaluationStatus.EVALUATED

    def ranked_ids(self) -> tuple[str, ...]:
        return tuple(item.candidate_id for item in self.ranked)

    def score_of(self, candidate_id: str) -> float | None:
        for item in self.ranked:
            if item.candidate_id == candidate_id:
                return item.score
        return None


class ObjectiveValue(BaseModel):
    """Raw objective observation. Missing values stay missing."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    indicator_id: str = Field(min_length=1)
    available: bool
    value: float | None = None
    unit: str | None = None


class ParetoPoint(BaseModel):
    """One candidate in objective space. No scalar score is attached."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    candidate_id: str = Field(min_length=1)
    objectives: tuple[ObjectiveValue, ...]
    nondominated: bool
    dominated_by: tuple[str, ...] = ()
    constraint_status: FeasibilityStatus


class MultiObjectiveResult(BaseModel):
    """Non-dominated set from raw objective values. Not a collapsed WSM score."""

    model_config = ConfigDict(frozen=True, extra="forbid")

    method: str = "pareto_nondominated"
    objectives: tuple[ObjectiveSpec, ...]
    points: tuple[ParetoPoint, ...] = ()
    omitted: tuple[OmittedCandidate, ...] = ()
    provenance: ProvenanceRecord
    status: EvaluationStatus = EvaluationStatus.EVALUATED

    def nondominated_ids(self) -> tuple[str, ...]:
        return tuple(item.candidate_id for item in self.points if item.nondominated)


def validate_decision_profile(
    profile: DecisionProfile, catalog: IndicatorRegistry | None = None
) -> None:
    """Reject unknown indicators and units that disagree with the registry."""

    table = default_registry if catalog is None else catalog
    for item in profile.criteria:
        spec = table.get(item.indicator_id)
        _check_numeric_indicator(item.indicator_id, spec)
        if item.unit != spec.unit:
            raise DecisionProfileError(
                f"{item.indicator_id}: weight unit {item.unit!r} "
                f"does not match indicator unit {spec.unit!r}"
            )


def validate_objectives(
    objectives: tuple[ObjectiveSpec, ...], catalog: IndicatorRegistry | None = None
) -> None:
    """Reject empty, duplicate, or non-numeric Pareto objectives."""

    if not objectives:
        raise RankingConfigError("Pareto analysis requires at least one objective")
    table = default_registry if catalog is None else catalog
    seen: set[str] = set()
    for item in objectives:
        if item.indicator_id in seen:
            raise RankingConfigError(f"duplicate objective {item.indicator_id!r}")
        seen.add(item.indicator_id)
        spec = table.get(item.indicator_id)
        _check_numeric_indicator(item.indicator_id, spec, RankingConfigError)
        if item.unit != spec.unit:
            raise RankingConfigError(
                f"{item.indicator_id}: objective unit {item.unit!r} "
                f"does not match indicator unit {spec.unit!r}"
            )


def _check_numeric_indicator(
    indicator_id: str,
    spec: IndicatorSpec,
    error: type[DecisionProfileError | RankingConfigError] = DecisionProfileError,
) -> None:
    if spec.unit == "categorical":
        raise error(f"{indicator_id} is categorical and cannot be used as a numeric criterion")
